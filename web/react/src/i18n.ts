export const dictionaries: Record<Lang, typeof fa> = { fa, en };

export type MessageKey = keyof typeof fa;

export function translate(lang: Lang, key: MessageKey, vars?: Record<string, string | number>) {
  let value = dictionaries[lang][key] ?? dictionaries.fa[key] ?? key;
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
  }
  return value;
}

